#!/usr/bin/env bash
# Build, start, authorize, map and replay ONE sweep target. Args: impl alpine pkgver port mport profile
# Writes suts/sweep/<impl>-<pkgver>/Dockerfile (records how obtained) and results/v2/B2/<impl>-<pkgver>.json
set -uo pipefail
cd "$(dirname "$0")/.."
IMPL=$1; AV=$2; PV=$3; PORT=$4; MPORT=$5; PROF=$6
NAME="b2-$IMPL-${PV%%-r*}"; D="suts/sweep/$IMPL-$PV"; mkdir -p "$D" results/v2/B2
DIG=$(docker inspect --format '{{index .RepoDigests 0}}' alpine:$AV)
VER=${PV%%_p*}; MAJ=${VER%%.*}; MIN=${VER#*.}; MIN=${MIN%%.*}
if [ "$IMPL" = openssh ]; then
  PSP=""; if [ "$MAJ" -gt 9 ] || { [ "$MAJ" -eq 9 ] && [ "$MIN" -ge 8 ]; }; then PSP="PerSourcePenalties no"; fi
  cat > "$D/Dockerfile" <<DF
# OpenSSH $PV from Alpine $AV (package openssh-server=$PV), base pinned by digest. Generated by harness/v2_sweep_one.sh.
FROM $DIG
RUN apk add --no-cache openssh-server=$PV openssh-keygen=$PV \\
 && adduser -D -s /bin/sh tester && echo 'tester:correct-horse-battery' | chpasswd \\
 && ssh-keygen -q -t rsa -b 3072 -N "" -f /etc/ssh/ssh_host_rsa_key && ssh-keygen -q -t ed25519 -N "" -f /etc/ssh/ssh_host_ed25519_key \\
 && mkdir -p /run/sshd /home/tester/.ssh && chown tester /home/tester/.ssh && chmod 700 /home/tester/.ssh \\
 && printf 'Port 22\nHostKey /etc/ssh/ssh_host_rsa_key\nHostKey /etc/ssh/ssh_host_ed25519_key\nPasswordAuthentication yes\nPubkeyAuthentication yes\nPermitRootLogin no\nMaxStartups 100:30:200\nLogLevel DEBUG3\n$PSP\n' > /etc/ssh/sshd_config
CMD ["/usr/sbin/sshd", "-D", "-e"]
DF
else
  cat > "$D/Dockerfile" <<DF
# Dropbear $PV from Alpine $AV (package dropbear=$PV), base pinned by digest. Generated by harness/v2_sweep_one.sh.
FROM $DIG
RUN apk add --no-cache dropbear=$PV \\
 && adduser -D -s /bin/sh tester && echo 'tester:correct-horse-battery' | chpasswd \\
 && mkdir -p /etc/dropbear /home/tester/.ssh && chown tester /home/tester/.ssh && chmod 700 /home/tester/.ssh \\
 && dropbearkey -t rsa -s 2048 -f /etc/dropbear/dropbear_rsa_host_key
CMD ["dropbear", "-F", "-E", "-w", "-p", "22", "-r", "/etc/dropbear/dropbear_rsa_host_key"]
DF
fi
echo "- $IMPL $PV: Alpine $AV package, base $DIG, mapper profile $PROF, SUT 127.0.0.1:$PORT, mapper $MPORT" > "$D/VERSION.md"
docker build -q -t "psm-$NAME:pinned" "$D" > /dev/null || { echo "$IMPL $PV BUILD-FAILED"; exit 1; }
docker rm -f "psm-$NAME" >/dev/null 2>&1
docker run -d --name "psm-$NAME" --restart unless-stopped -p 127.0.0.1:$PORT:22 --memory 128m --cpus 1 "psm-$NAME:pinned" >/dev/null
sleep 2; bash suts/authorize.sh "psm-$NAME" || echo "$IMPL $PV AUTHORIZE-FAILED"
bash harness/start_mapper.sh "$NAME" "$MPORT" "$PORT" Dropbear "$PROF" >/dev/null
sleep 2
.venv/bin/python -m psm.replay --target "$IMPL-${PV%%-r*}=$MPORT:psm-$NAME" --reps 3 --seq-file reference/final_check_seqs.json \
  --out "results/v2/B2/$IMPL-$PV.json" > "results/v2/B2/$IMPL-$PV.log" 2>&1 && echo "$IMPL $PV OK" || echo "$IMPL $PV REPLAY-FAILED"
