"""Tabulate the research-loop cost: per learning run (results/learning/*/stats.json + nondet/harness logs) and
per SUT the mapper fixes / human corrections from results/loopcost.jsonl.  Writes results/loopcost_table.md."""
import json
from collections import defaultdict
from pathlib import Path

L = Path("results/learning")


def count_lines(p):
    return sum(1 for _ in open(p)) if p.exists() else 0


def run_rows():
    rows = []
    for st in sorted(L.glob("*/stats*.json")):
        s = json.loads(st.read_text())
        d = st.parent
        rows.append({
            "run": d.name + ("" if st.name == "stats.json" else f" ({st.stem.replace('stats_', '')})"),
            "inputs": len(s["alphabet"]), "states": s["states"], "rounds": s.get("learning_rounds"),
            "oracle": s.get("eq_oracle", {}).get("type", "random"),
            "mq": s.get("aalpy_queries_learning"), "eq": s.get("aalpy_queries_eq_oracle"),
            "sut_q": s["sut"].get("sut_queries", 0), "sut_steps": s["sut"].get("sut_steps", 0),
            "cache_hits": s["sut"].get("cache_hits", 0) + s["sut"].get("sink_shortcuts", 0),
            "nondet": s["sut"].get("nondet_events", 0), "harness_err": s["sut"].get("harness_errors", 0),
            "minutes": round(s["seconds"] / 60, 1),
        })
    return rows


def main():
    rows = run_rows()
    ev = [json.loads(l) for l in open("results/loopcost.jsonl") if l.strip()]
    per = defaultdict(lambda: defaultdict(int))
    for e in ev:
        per[e["sut"]][e["kind"]] += 1
    out = ["# Research-loop cost (generated by psm/costs.py)", "",
           "## Learning runs", "",
           "| run | inputs | states | rounds | oracle | AALpy MQ | AALpy EQ | SUT queries | SUT steps | answered from cache | nondet events | harness errors | minutes |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append("| {run} | {inputs} | {states} | {rounds} | {oracle} | {mq} | {eq} | {sut_q} | {sut_steps} | {cache_hits} | {nondet} | {harness_err} | {minutes} |".format(**r))
    out += ["", "## Interventions (results/loopcost.jsonl)", "",
            "| SUT | mapper fixes | harness fixes | human corrections |", "|---|---|---|---|"]
    for sut, k in sorted(per.items()):
        out.append(f"| {sut} | {k['mapper_fix']} | {k['harness_fix']} | {k['human_correction']} |")
    out += ["", "| time | SUT | kind | who | what |", "|---|---|---|---|---|"]
    for e in ev:
        out.append(f"| {e['time']} | {e['sut']} | {e['kind']} | {e['who']} | {e['what']} |")
    Path("results/loopcost_table.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
