"""Build results/SUMMARY.md from the learned models and the replay-verified catalogue results.

    uv run python scripts/summarize.py

For each target, the latest run (highest version label) with a model is used,
and its verdicts come from the newest verification file that covers that model.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results" / "runs"
CAT = ROOT / "results" / "catalogue"


def latest_runs():
    best = {}
    for d in RUNS.iterdir():
        m = re.fullmatch(r"(.+)-v(\d+)vm", d.name)
        if not m or not (d / "learn.json").exists():
            continue
        name, ver = m.group(1), int(m.group(2))
        if name not in best or ver > best[name][0]:
            best[name] = (ver, d)
    return {k: v[1] for k, v in sorted(best.items())}


def verdicts():
    out = {}
    for f in sorted(CAT.glob("verified-*.json"), key=lambda p: p.stat().st_mtime):
        for model, hits in json.loads(f.read_text()).items():
            out[Path(model).parent.name] = hits   # newer files override older ones
    return out


def main():
    runs, ver = latest_runs(), verdicts()
    rows = ["| Target | Source | States | Learn time | Queries (MQ+EQ) | Nondet. | Confirmed catalogue hits | Refuted |",
            "|---|---|---|---|---|---|---|---|"]
    for name, d in runs.items():
        s = json.loads((d / "learn.json").read_text())
        hits = ver.get(d.name)
        if hits is None:
            conf, ref = "not verified yet", ""
        else:
            conf = ", ".join(f"`{h['pattern']}`" for h in hits if h["verdict"] == "CONFIRMED") or "none"
            ref = str(sum(h["verdict"] == "REFUTED" for h in hits))
        src = re.split(r" \(|;|, https?:| https?:", s["source"])[0]
        rows.append(f"| {name} | {src} | {s['states']} | {s['seconds']:.0f} s | {s['mq'] + s['eq']} | "
                    f"{s['nondet_events']} | {conf} | {ref} |")
    text = ("# Results summary\n\n"
            "Generated by `scripts/summarize.py` from `results/runs/*/learn.json` and `results/catalogue/verified-*.json`.\n"
            "Every catalogue hit was replayed 3× on a fresh container (`src/smlearn/verify.py`); only CONFIRMED hits are real behaviour.\n"
            "Refuted hits are model errors and were fed back to the learner as seeds.\n\n" + "\n".join(rows) + "\n")
    (ROOT / "results" / "SUMMARY.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
